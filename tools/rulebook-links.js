"use strict";
// Build-time only. No rulebook text, logo, remote embed or automatic request.
const fs = require("node:fs"), path = require("node:path");
const ROOT = path.resolve(__dirname, "..");
const books = require("../docs/rulebooks.json");
const esc = s => String(s).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
for (const b of books) {
  const u = new URL(b.url);
  if(u.protocol !== "https:" || u.hostname !== "www.nxlpaintball.com" || u.username || u.password || u.search || u.hash)
    throw new Error("Rulebook links must use the official HTTPS source.");
}
const markup = '<p class="rules-note">Open the official rulebook for your format. A connection is needed; save the PDF on your device before the event.</p>'
  + '<div class="rules-books">' + books.map(b => '<a class="rules-book" href="'+esc(b.url)+'" target="_blank" rel="noopener noreferrer"><b>'+esc(b.name)+'</b><span>'+esc(b.formats)+'</span><span>'+esc(b.edition)+' · Official NXL rulebook · Opens a new tab</span></a>').join('') + '</div>'
  + '<p class="rules-note">Check the edition and event updates with the organizer. Officials make the live call.</p>';
const css = '.rules-books{display:grid;gap:12px}.rules-book{display:flex;flex-direction:column;gap:6px;min-height:44px;padding:16px;border:1px solid #3a3f40;border-radius:12px;background:#111314;color:#efedeb;text-decoration:none;overflow-wrap:anywhere}.rules-book span,.rules-note{color:#ff5a52}.rules-book:focus-visible{outline:3px solid #efedeb;outline-offset:2px}.rules-note{max-width:65ch;line-height:1.5;margin:12px 0}';
const start = '<!-- rulebook-links:begin — generated by tools/rulebook-links.js -->';
const end = '<!-- rulebook-links:end -->';
function preview(src) {
  const block = start+'\n<style>'+css+'#rulebooksDialog{width:min(620px,calc(100% - 24px));max-height:85dvh;overflow:auto;border:1px solid #3a3f40;border-radius:16px;padding:20px;background:#0b0c0d;color:#efedeb}#rulebooksDialog::backdrop{background:#000b}#rulebooksDialog button,#rulebooksOpen{min-width:44px;min-height:44px}#rulebooksDialog h2{margin:0 0 12px}#rulebooksOpen{margin:6px 0}</style>\n'
    + '<dialog id="rulebooksDialog" aria-labelledby="rulebooksTitle"><h2 id="rulebooksTitle">Rules</h2>'+markup+'<form method="dialog"><button class="ld" autofocus>Close</button></form></dialog>\n'
    + '<script>(function(){const header=document.querySelector("header"),dialog=document.getElementById("rulebooksDialog"),button=document.createElement("button");button.id="rulebooksOpen";button.className="ld";button.textContent="Rules";button.setAttribute("aria-haspopup","dialog");header.appendChild(button);button.addEventListener("click",()=>dialog.showModal());dialog.addEventListener("close",()=>button.focus());})();</script>\n'+end;
  const a=src.indexOf(start), b=src.indexOf(end);
  if(a>=0 && b>a) return src.slice(0,a)+block+src.slice(b+end.length);
  if(!src.includes('</body>')) throw new Error('Preview has no body end.');
  return src.replace('</body>', block+'\n</body>');
}
function coach(src) {
  const a='/* rulebook-links:begin — generated by tools/rulebook-links.js */',b='/* rulebook-links:end */';
  const block=a+'\nfunction rulebooksPage(){return sec("Rules",'+JSON.stringify('<style>'+css+'</style>'+markup)+');}\n'+b;
  const i=src.indexOf(a),j=src.indexOf(b);
  if(i>=0 && j>i)return src.slice(0,i)+block+src.slice(j+b.length);
  if(!src.includes('const MORE_GROUPS=['))throw new Error('Coach menu not found.');
  return src.replace('const MORE_GROUPS=[',block+'\nconst MORE_GROUPS=[');
}
if(require.main===module){
  const check=process.argv.includes('--check');let stale=0;
  for(const file of ['web/index.html','teasers/player/index.html','teasers/team/index.html']){
    const p=path.join(ROOT,file),before=fs.readFileSync(p,'utf8'),after=file.startsWith('web/')?coach(before):preview(before);
    if(before!==after){stale++;if(!check)fs.writeFileSync(p,after);}
    console.log(file+': '+(before===after?'up to date':check?'out of date — run node tools/rulebook-links.js':'written'));
  }
  if(check&&stale)process.exitCode=1;
}
module.exports={preview,coach,markup,books};
