function apply(src) {
  const block = build();
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a >= 0 && b > a) src = src.slice(0, a) + block + src.slice(b + END.length);
  else {
    const at = src.indexOf("const FREE_LAYOUT=");
    if (at < 0) throw new Error("teaser has no FREE_LAYOUT to put the fields before");
    src = src.slice(0, at) + block + "\n" + src.slice(at);
  }
  // Twice: the old fields' comments sit between their lists until those go.
  for (const [rx, to] of MIGRATE) src = src.replace(rx, to);
  src = dropRaw(src);
  for (const [rx, to] of MIGRATE) src = src.replace(rx, to);
  return patchCode(src);
}

const check = process.argv.includes("--check");
let stale = 0;
for (const file of TEASERS) {
  const rel = path.relative(ROOT, file);
  const before = fs.readFileSync(file, "utf8");
  const after = apply(before);
  if (after !== before) stale++;
  if (!check && after !== before) fs.writeFileSync(file, after);
  console.log(`${rel}: ${after === before ? "up to date" : check ? "out of date — run node tools/teaser_fields.js" : "written"}`);
}
if (check && stale) process.exit(1);
