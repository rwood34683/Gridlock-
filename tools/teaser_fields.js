#!/usr/bin/env node
/* Put the coach app's measured fields, break plants, team board and marks into
 * the Team and Player previews (teasers/<kind>/index.html).
 *
 *   node tools/teaser_fields.js            write it
 *   node tools/teaser_fields.js --check    say whether it is up to date
 *
 * The preview shipped with July's events (Cincinnati, Seffner, a Texas trace,
 * Dreux) and a PBLeagues snapshot with season points. The coach app is the
 * source of truth for fields: every bunker here is the coach app's own record,
 * read out of web/index.html, never typed. The block between the markers is
 * generated; never hand-edit it. A preview field is drawn to its measured
 * footprint in the paint the map printed, and its twelve breaks plant where
 * BREAK_PLANTS puts them.
 *
 * The team board carries names and registration only. Points were the
 * league's rankings and threat was seeded from them; the coach app scores
 * nothing for a coach, so neither does the preview.
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const APP = path.join(ROOT, "web/index.html");
const TEASERS = ["player", "team"].map(k => path.join(ROOT, `teasers/${k}/index.html`));
const DRAW = path.join(__dirname, "teaser_draw.js");
const BEGIN = "/* coachfields:begin — generated by tools/teaser_fields.js, never hand-edit */";
const END = "/* coachfields:end */";

function grab(src, name) {
  const i = src.indexOf(`const ${name} = `);
  if (i < 0) throw new Error(`web/index.html has no ${name}`);
  let j = src.indexOf("=", i) + 1;
  while (src[j] === " ") j++;
  const open = src[j], close = open === "[" ? "]" : "}";
  let d = 0, k = j, q = null;
  for (; k < src.length; k++) {
    const c = src[k];
    if (q) { if (c === "\\") { k++; continue; } if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === "`") { q = c; continue; }
    if (c === "/" && src[k + 1] === "/") { k = src.indexOf("\n", k); continue; }
    if (c === "/" && src[k + 1] === "*") { k = src.indexOf("*/", k) + 1; continue; }
    if (c === open) d++;
    else if (c === close && --d === 0) break;
  }
  return src.slice(j, k + 1);
}

function coachData() {
  const src = fs.readFileSync(APP, "utf8");
  const ctx = {};
  vm.createContext(ctx);
  const arrays = [...grab(src, "LAYOUTS").matchAll(/bunkers:([A-Z]+)/g)].map(m => m[1]);
  for (const n of [...arrays, "BREAK_PLANTS", "WCUP", "DIVISIONS"]) vm.runInContext(`var ${n} = ${grab(src, n)};`, ctx);
  vm.runInContext(`var LAYOUTS = ${grab(src, "LAYOUTS")};`, ctx);
  return ctx;
}

// The preview's names for three of the twelve.
const PLAY_KEY = { conserve: "cons", trade: "clean", lock: "lanes" };

function build() {
  const c = coachData();
  const fields = {}, plays = {};
  // The current event first: it is the field a new phone opens on.
  const keys = Object.keys(c.LAYOUTS).sort((a, b) => (b === "nwc") - (a === "nwc"));
  for (const k of keys) {
    const L = c.LAYOUTS[k];
    const when = String(L.when || "").split(" · ")[0];
    // The preview's frame counts y up from the snake side; the coach app's
    // counts down from the dorito side. Screen space is the same in both, so
    // an angle carries over unchanged.
    const raw = L.bunkers.map(b => {
      const o = { n: b.n, x: b.x, y: +(120 - b.y).toFixed(2), t: b.t, w: b.w, h: b.h, c: b.c || "n", m: 1 };
      if (b.a) o.a = b.a;
      if (b.k) o.k = b.k;
      if (b.d) o.d = b.d;
      return o;
    });
    fields[k] = { name: L.name, sub: when || (L.season ? String(L.season) : ""), src: L.source || "", raw, full: true, measured: true };
    const byId = Object.fromEntries(L.bunkers.map(b => [b.id, b]));
    const set = {};
    for (const [call, ids] of Object.entries(c.BREAK_PLANTS[k] || {})) {
      const players = ids.map((id, i) => {
        const b = byId[id];
        if (!b) throw new Error(`${k} ${call}: no bunker ${id}`);
        const wire = b.x < 22 ? "back" : b.y >= 84 ? "S" : b.y <= 36 ? "D" : "C";
        return { f: [2, 14 + i * 22], t: [b.x, +(120 - b.y).toFixed(2)], w: wire, e: `${b.n} (${id})` };
      });
      set[PLAY_KEY[call] || call] = { players };
    }
    plays[k] = set;
  }
  const divs = [];
  for (const d of c.WCUP.divs) divs.push({ d: `World Cup · ${d.name}`, t: d.teams.map(([n, reg]) => [n, "", reg === "PAID" ? 1 : 0, 0]) });
  for (const d of c.DIVISIONS) {
    const where = d.id === "pro" ? "Lone Star" : /^wc-/.test(d.id) ? "WCPPL Championship" : "";
    divs.push({ d: (where ? where + " · " : "") + d.name, t: d.teams.map(t => [t.name, "", t.reg === "PAID" || !t.reg ? 1 : 0, 0]) });
  }
  const json = v => JSON.stringify(v);
  return [
    BEGIN,
    `const COACH_FIELDS=${json(fields)};`,
    `const COACH_PLAYS=${json(plays)};`,
    `const COACH_DIVS=${json(divs.filter(d => d.t.length))};`,
    fs.readFileSync(DRAW, "utf8").trimEnd(),
    END,
  ].join("\n");
}

