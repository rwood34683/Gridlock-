// The old fields' bunker lists, now unread.
function dropRaw(src) {
  for (const n of ["RAW_CIN", "RAW_SEF", "RAW_TEX", "RAW_EUR"]) {
    const i = src.indexOf(`const ${n}=[`);
    if (i < 0) continue;
    let d = 0, k = src.indexOf("[", i);
    for (; k < src.length; k++) { if (src[k] === "[") d++; else if (src[k] === "]" && --d === 0) break; }
    let e = k + 1;
    if (src[e] === ";") e++;
    if (src[e] === "\n") e++;
    src = src.slice(0, i) + src.slice(e);
  }
  return src;
}

